# -*- coding: utf-8 -*-
"""
core/CADConverter.py - Headless DXF to G-code (ISO 6983) converter.

Runs ``FreeCADcmd`` through ``subprocess.run`` and executes an in-memory script
(passed with ``-c``, so no temporary files are created) that:

1. Imports the DXF into a new FreeCAD document.
2. Collects every edge, chains them into wires and discretizes them.
3. Builds the cutting toolpath with the FreeCAD Path/CAM module
   (``Path.Command`` / ``Path.Path``).
4. Writes standard ISO 6983 G-code exactly to ``output_gcode_path``.

Usage:
    converter = CADConverter(timeout_s=30.0)
    converter.dxf_to_gcode("part.dxf", "part.gcode")
"""

from __future__ import annotations

import os
import shutil
import subprocess
from typing import Any, Dict, Optional

from core.config_loader import load_hardware_config

_ALLOWED_EXTENSIONS = (".gcode", ".nc")

# Script executed inside FreeCAD. Parameters are received via environment
# variables to avoid any quoting/escaping problems with Windows paths.
_FREECAD_SCRIPT = r'''
import os, sys, traceback

def _run():
    import FreeCAD, Part
    try:
        import Path as PathMod
    except ImportError:
        import CAM as PathMod

    dxf_path = os.environ["CADC_DXF"]
    out_path = os.environ["CADC_OUT"]
    feed = float(os.environ["CADC_FEED"])
    rapid = float(os.environ["CADC_RAPID"])
    deflection = float(os.environ["CADC_DEFLECTION"])
    join_tol = float(os.environ["CADC_JOIN_TOL"])

    doc = FreeCAD.newDocument("CADConverter")
    try:
        import importDXF
        importDXF.insert(dxf_path, doc.Name)
    except Exception:
        import Import
        Import.insert(dxf_path, doc.Name)
    doc.recompute()

    edges = []
    for obj in doc.Objects:
        shape = getattr(obj, "Shape", None)
        if shape is not None and not shape.isNull():
            edges.extend(shape.Edges)
    if not edges:
        raise RuntimeError("No geometry found in DXF file: " + dxf_path)

    wires = [w for w in Part.sortEdges(edges)]
    commands = []
    cursor = None
    for edge_list in wires:
        wire = Part.Wire(edge_list)
        pts = wire.discretize(Deflection=deflection)
        if len(pts) < 2:
            continue
        start = pts[0]
        # Rapid move (laser off) only when we are not already at the start point
        if cursor is None or cursor.distanceToPoint(start) > join_tol:
            commands.append(PathMod.Command("M5"))
            commands.append(PathMod.Command("G0", {"X": start.x, "Y": start.y, "F": rapid}))
        commands.append(PathMod.Command("M3"))
        first = True
        for p in pts[1:]:
            params = {"X": p.x, "Y": p.y}
            if first:
                params["F"] = feed
                first = False
            commands.append(PathMod.Command("G1", params))
        cursor = pts[-1]
    commands.append(PathMod.Command("M5"))

    toolpath = PathMod.Path(commands)

    def _fmt(v):
        return ("%.4f" % v).rstrip("0").rstrip(".")

    lines = ["%", "(Generated by CADConverter via FreeCAD)", "G21", "G90", "G17"]
    for cmd in toolpath.Commands:
        words = [cmd.Name]
        for key in ("X", "Y", "F"):
            if key in cmd.Parameters:
                words.append(key + _fmt(cmd.Parameters[key]))
        lines.append(" ".join(words))
    lines += ["M2", "%"]

    with open(out_path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")

try:
    _run()
    code = 0
except Exception:
    sys.stderr.write("CADConverter error: " + traceback.format_exc())
    code = 1
sys.stdout.flush()
sys.stderr.flush()
os._exit(code)
'''


class CADConverter:
    """Converts DXF drawings into ISO 6983 G-code using headless FreeCAD."""

    def __init__(
        self,
        freecad_cmd: Optional[str] = None,
        timeout_s: Optional[float] = None,
        feed_rate: float = 100.0,
        rapid_rate: float = 300.0,
        deflection: float = 0.01,
        join_tolerance: float = 1e-4,
        config: Optional[Dict[str, Any]] = None,
        config_path: Optional[str] = None,
    ) -> None:
        """
        freecad_cmd: Executable name or full path of ``FreeCADcmd``.
        timeout_s: Maximum seconds to wait for FreeCAD before aborting.
        feed_rate: Cutting feed rate written on G1 moves (units/min).
        rapid_rate: Feed rate written on G0 moves (units/min).
        deflection: Max curve discretization error in drawing units.
        join_tolerance: Distance below which consecutive paths are considered connected (no rapid move emitted).
        config: Optional configuration dictionary.
        config_path: Optional explicit path to hardware_config.json.
        """
        cfg = config if config is not None else load_hardware_config(config_path)
        self.config: Dict[str, Any] = cfg
        cad_cam_cfg = cfg.get("cad_cam", {})

        if freecad_cmd is None:
            freecad_cmd = str(cad_cam_cfg.get("freecad_cmd", "FreeCADcmd"))
        if timeout_s is None:
            timeout_s = float(cad_cam_cfg.get("timeout_seconds", 30.0))

        self.freecad_cmd: str = freecad_cmd
        self.timeout_s: float = timeout_s
        self.feed_rate: float = feed_rate
        self.rapid_rate: float = rapid_rate
        self.deflection: float = deflection
        self.join_tolerance: float = join_tolerance

    def dxf_to_gcode(self, dxf_path: str, output_gcode_path: str) -> str:
        """Convert a DXF file to G-code.
            dxf_path: Path to an existing, non-empty DXF file.
            output_gcode_path: Explicit destination path (``.gcode`` or ``.nc``).
        Returns:
            The absolute path of the generated G-code file.
        Raises:
            FileNotFoundError: DXF missing/empty or FreeCADcmd not found.
            ValueError: Output path undefined or with an invalid extension.
            RuntimeError: FreeCAD failed, produced no output or timed out.
        """
        if not dxf_path or not os.path.isfile(dxf_path) or os.path.getsize(dxf_path) == 0:
            raise FileNotFoundError(f"DXF file not found or empty: {dxf_path!r}")

        if output_gcode_path is None or not str(output_gcode_path).strip():
            raise ValueError("output_gcode_path must be explicitly specified.")

        if not output_gcode_path.lower().endswith(_ALLOWED_EXTENSIONS):
            raise ValueError(
                f"output_gcode_path must end with one of {_ALLOWED_EXTENSIONS}: {output_gcode_path!r}"
            )

        executable = shutil.which(self.freecad_cmd)
        if executable is None:
            # Fallback check for standard Windows FreeCAD install directories
            candidates = [
                r"C:\Program Files\FreeCAD 1.0\bin\FreeCADcmd.exe",
                r"C:\Program Files\FreeCAD 0.21\bin\FreeCADcmd.exe",
                r"C:\Program Files\FreeCAD\bin\FreeCADcmd.exe",
                os.path.expandvars(r"%LOCALAPPDATA%\Programs\FreeCAD 1.0\bin\FreeCADcmd.exe"),
            ]
            executable = next((p for p in candidates if os.path.isfile(p)), None)
        if executable is None:
            raise FileNotFoundError(f"FreeCAD executable not found: {self.freecad_cmd!r}")

        dxf_abs = os.path.abspath(dxf_path)
        out_abs = os.path.abspath(output_gcode_path)
        out_dir = os.path.dirname(out_abs)
        if out_dir:
            os.makedirs(out_dir, exist_ok=True)

        # Remove stale output so a failed run can never be mistaken for success.
        if os.path.isfile(out_abs):
            os.remove(out_abs)

        env: Dict[str, str] = os.environ.copy()
        env.update({
            "CADC_DXF": dxf_abs,
            "CADC_OUT": out_abs,
            "CADC_FEED": repr(float(self.feed_rate)),
            "CADC_RAPID": repr(float(self.rapid_rate)),
            "CADC_DEFLECTION": repr(float(self.deflection)),
            "CADC_JOIN_TOL": repr(float(self.join_tolerance)),
        })

        try:
            result: Optional[subprocess.CompletedProcess] = subprocess.run(
                [executable, "-c", _FREECAD_SCRIPT],
                capture_output=True,
                text=True,
                timeout=self.timeout_s,
                env=env,
                check=False,
            )
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError(
                f"FreeCAD conversion timed out after {self.timeout_s} seconds."
            ) from exc

        if result.returncode != 0:
            message = (result.stderr or result.stdout or "").strip() or "unknown error"
            raise RuntimeError(
                f"FreeCAD failed (exit code {result.returncode}): {message}"
            )

        if not os.path.isfile(out_abs) or os.path.getsize(out_abs) == 0:
            raise RuntimeError(
                "FreeCAD finished without errors but no G-code was produced: "
                f"{(result.stdout or '').strip()}"
            )

        return out_abs
